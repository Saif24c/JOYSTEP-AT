"""Hardware and side-effect seams.

These protocols intentionally contain no implementation policy.  The current
application continues using its existing libraries through real adapters; test
code can supply fakes without a camera, microphone, desktop input, or speaker.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol, Sequence


class Clock(Protocol):
    def monotonic(self) -> float: ...
    def sleep(self, seconds: float) -> None: ...


class Camera(Protocol):
    def read(self) -> tuple[bool, Any]: ...
    def release(self) -> None: ...


class HandTracker(Protocol):
    def process(self, rgb_frame: Any) -> Any: ...
    def close(self) -> None: ...


class FaceTracker(Protocol):
    def process(self, rgb_frame: Any) -> Any: ...
    def close(self) -> None: ...


class InputController(Protocol):
    def move_to(self, x: int, y: int, **kwargs: Any) -> None: ...
    def click(self, button: str = "left") -> None: ...
    def scroll(self, amount: int) -> None: ...
    def type_text(self, text: str, **kwargs: Any) -> None: ...
    def hotkey(self, *keys: str) -> None: ...
    def screenshot(self) -> Any: ...


class Recognizer(Protocol):
    def listen(self, timeout: float, phrase_time_limit: float) -> Any: ...
    def recognize(self, audio: Any) -> str: ...


class TextToSpeech(Protocol):
    def say(self, text: str, priority: bool = False) -> None: ...
    def stop(self) -> None: ...


class ScreenCapture(Protocol):
    def capture(self) -> Any: ...


class SystemActions(Protocol):
    def shutdown(self) -> None: ...
    def cancel_shutdown(self) -> None: ...
    def restart(self) -> None: ...
    def sleep(self) -> None: ...
    def lock(self) -> None: ...
    def open_application(self, name: str) -> bool: ...


@dataclass
class RuntimeSeams:
    """Dependency bundle used by tests and later extraction work.

    It is deliberately additive in Stage 1: introducing it does not replace
    the live runtime's device lifecycle or user-facing controls.
    """
    clock: Clock | None = None
    camera: Camera | None = None
    hand_tracker: HandTracker | None = None
    face_tracker: FaceTracker | None = None
    input: InputController | None = None
    recognizer: Recognizer | None = None
    tts: TextToSpeech | None = None
    screen_capture: ScreenCapture | None = None
    system: SystemActions | None = None

